#!/usr/bin/env python3
"""Compile the GPU mode-5 objects (GMU SMMU context on the GMU pool) against the recorded XNU recipes.

As UniXNU-asteroids scripts/build-native-legacy-display.py does for its probe: NativeAdreno's memory, VM and
SMMU-context classes with NativeAdrenoGmuContextBringup and NativeAdrenoCpu.cpp's cache queries, plus UniXNU's
ArmSmmu4K kit. Sources: rootstockos/NativeAdreno at asteroids' pin 5e2b23e (.scratch/gpu-src/NativeAdreno),
UniXNU kits/ArmSmmu4K, kits/Sm7635Platform (.scratch/sm7635-reference) and ShengGmuSource.h generated by
asteroids' prepare-asteroids-gmu.py from amethyst's gen80300 firmware (equal to asteroids' pins).
Third-party sources keep their own warning policy (no -Werror)."""
import importlib.util, subprocess
from pathlib import Path

KIT = Path(__file__).resolve().parent
PROJECT = KIT.parents[2]
spec = importlib.util.spec_from_file_location('compile_touch', KIT / 'compile-touch.py')
ct = importlib.util.module_from_spec(spec); spec.loader.exec_module(ct)

ADRENO = PROJECT / '.scratch/gpu-src/NativeAdreno'
SMMU4K = PROJECT / '.scratch/gpu-src/ArmSmmu4K'   # UniXNU components.toml pin 83969cd (the tree's copy predates ArmSmmu4KTablePages)
SOC = PROJECT / '.scratch/sm7635-reference/kits/Sm7635Platform'
GEN = PROJECT / '.scratch/gmu-gen/build/sheng-gmu'
OUT = PROJECT / '.scratch/ufs-audit/gpu'
HFI = PROJECT / 'UniXNU-amethyst/kits/AdrenoFirmware'   # rootstockos/AdrenoFirmware 96028a5, asteroids' pin
# Mode 6: the command DB parser, the vote builder and the HFI startup table (asteroids' vote_sources)
KIT_C = [KIT / 'ShengGmuVotes.c', SOC / 'ShengGmuCommandDb.c', HFI / 'AdrenoHfiVotes.c', HFI / 'AdrenoHfiStartup.c',
         HFI / 'AdrenoHfi.c', SOC / 'ShengGmu.c', HFI / 'AdrenoFirmware.c']
CPP = ['NativeAdrenoMemory', 'NativeAdrenoSmmuMemory', 'NativeAdrenoVm', 'NativeAdrenoGmuMemory',
       'NativeAdrenoSmmuContext', 'NativeAdrenoGmuContext', 'NativeAdrenoCpu', 'NativeAdrenoSha256',
       # V42: asteroids' remaining gmu_sources for modes 12-18 (ring, CP init, power-up list, submit, timer, user client)
       'NativeAdrenoGpuContext', 'NativeAdrenoRing', 'NativeAdrenoCpInit', 'NativeAdrenoPwrup', 'NativeAdrenoSubmit',
       'NativeAdrenoTimer', 'NativeAdrenoProfile', 'NativeAdrenoUserClient', 'NativeAdrenoPublish']
PM4 = PROJECT / 'UniXNU/kits/AdrenoPM4'
# V42: the probe itself (asteroids' GpuPowerProbe.cpp, third-party warning policy) and the SMC helper
PROBE_CPP = [KIT / 'GpuPowerProbe.cpp', KIT / 'KeyStoreProbe.cpp']
# V47: UniXNU's AppleKeyStoreState stand-in, its static initializer removed (KeyStoreProbe registers the class), as asteroids builds it
AKS = PROJECT / 'UniXNU/drivers/AppleKeyStoreState/NativeKeyStoreEvents.cpp'
FLAGS = ['-mgeneral-regs-only', '-I', str(ct.TREE / '.cache/xnu-work/osfmk'), '-I', str(KIT),
         '-I', str(ADRENO), '-I', str(SMMU4K), '-I', str(SOC), '-I', str(GEN), '-I', str(HFI), '-I', str(PM4), '-Wno-incompatible-sysroot',
         '-DSHENG_GMU_POOL_BASE=UINT64_C(0xe6440000)', '-DSHENG_GMU_POOL_BYTES=0x2000000u']

def compile_with(recipe, src, obj):
    record = ct.load_recipe(recipe)
    kept = [a for a in record['arguments'] if a.startswith('-Wno-')]
    ct.build_log.compile_command(record, src, obj, FLAGS + kept, False)

def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name in CPP:
        compile_with(ct.RECIPE_CPP, ADRENO / (name + '.cpp'), OUT / (name + '.o')); print('PASS: compiled', name)
    for src in PROBE_CPP:
        compile_with(ct.RECIPE_CPP, src, OUT / (src.stem + '.o')); print('PASS: compiled', src.name)
    obj = OUT / 'NativeKeyStoreEvents.o'
    compile_with(ct.RECIPE_CPP, AKS, obj)
    subprocess.run(['llvm-objcopy', '--remove-section=__DATA,__mod_init_func',
                    '--globalize-symbol=__GLOBAL__sub_I_NativeKeyStoreEvents.cpp', str(obj), str(OUT / 'NativeKeyStoreEvents.late.o')], check=True)
    obj.unlink()
    print('PASS: compiled NativeKeyStoreEvents.cpp (late)')
    for src in [PM4 / 'AdrenoPM4.c', KIT / 'AmethystSmc.c', KIT / 'AmethystGpuStandins.c']:
        compile_with(ct.RECIPE_C, src, OUT / (src.stem + '.kit.o')); print('PASS: compiled', src.name)
    for src in KIT_C:
        compile_with(ct.RECIPE_C, src, OUT / (src.stem + '.kit.o')); print('PASS: compiled', src.name)
    for src in sorted(SMMU4K.glob('ArmSmmu4K*.c')):
        compile_with(ct.RECIPE_C, src, OUT / (src.stem + '.o')); print('PASS: compiled', src.name)

if __name__ == '__main__':
    main()
